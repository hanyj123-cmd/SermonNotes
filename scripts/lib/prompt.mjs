export function buildUserMessage({ category, title, publishedAt, transcript }) {
  const label = CATEGORY_LABELS[category] || category;
  return `다음은 교회 유튜브 영상의 자막입니다. 위 지침에 따라 JSON으로 정리해 주세요.

[예배 구분] ${label}
[영상 제목] ${title}
[게시일] ${publishedAt || '알 수 없음'}

[자막 시작]
${transcript}
[자막 끝]`;
}

